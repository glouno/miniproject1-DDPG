"""Load complete pilot runs and generate transparent seed-level analysis.

Figures are generated by ../report/scripts/lunarlander_pilot.py. No p-values
are inferred from correlated trajectory points. This module also supports
analysis.ipynb, whose outputs are rebuilt from saved raw experiment data.
"""
import csv
import json
from pathlib import Path
import numpy as np
import matplotlib.pyplot as plt

COLORS={False:'#2874a6',True:'#d56c21'}


def load_pilot(root):
    root=Path(root)
    manifest=json.loads((root/'manifest.json').read_text())
    runs=[]
    for job in manifest['jobs']:
        directory=root/job['directory']
        assert (directory/'summary.json').exists(),f'Incomplete run: {directory}'
        metadata=json.loads((directory/'metadata.json').read_text())
        assert metadata['source_sha256']==manifest['experiment_sha256']
        metrics=[json.loads(line) for line in (directory/'metrics.jsonl').read_text().splitlines()]
        assert [m['step'] for m in metrics]==[0,10000,20000,30000,40000,50000]
        cfg=metadata['config']
        assert cfg['seed']==job['seed'] and cfg['algorithm']==job['algorithm']
        assert cfg['layer_norm']==job['layer_norm']
        long=json.loads((directory/'calibration-long/metrics.json').read_text())
        runs.append(dict(directory=directory,config=cfg,metrics=metrics,long=long))
    assert len(runs)==manifest['expected_runs']==12
    return manifest,runs


def group(runs,algorithm,layer_norm):
    return sorted([r for r in runs if r['config']['algorithm']==algorithm and
                   r['config']['layer_norm']==layer_norm],key=lambda r:r['config']['seed'])


def mean_sd(values):
    return float(np.mean(values)),float(np.std(values,ddof=1))


def summaries(runs):
    rows=[]
    for algo in ('ddpg','td3'):
        for ln in (False,True):
            selected=group(runs,algo,ln)
            returns=[r['long']['eval_return'] for r in selected]
            bias=[r['long']['bias_q1'] for r in selected]
            rmse=[r['long']['rmse_q1'] for r in selected]
            auc=[np.trapezoid([m['eval_return'] for m in r['metrics']],
                             [m['step'] for m in r['metrics']])/50000 for r in selected]
            row=dict(algorithm=algo,layer_norm=ln,n_seeds=len(selected))
            for key,values in [('return',returns),('bias_q1',bias),('rmse_q1',rmse),('normalized_auc',auc)]:
                row[key+'_mean'],row[key+'_sd']=mean_sd(values)
            row['censored_10000']=sum(r['long']['censored_10000'] for r in selected)
            rows.append(row)
    return rows


def paired_effects(runs):
    rows=[]
    for algo in ('ddpg','td3'):
        off=group(runs,algo,False)
        on=group(runs,algo,True)
        for metric in ('eval_return','bias_q1','rmse_q1'):
            differences=[b['long'][metric]-a['long'][metric] for a,b in zip(off,on)]
            mean,sd=mean_sd(differences)
            rows.append(dict(algorithm=algo,metric=metric,mean_difference=mean,
                             sd_difference=sd,seed_differences=differences))
    return rows


def savefig(fig,destination,name):
    destination=Path(destination)
    destination.mkdir(parents=True,exist_ok=True)
    fig.savefig(destination/(name+'.png'),dpi=160,bbox_inches='tight')
    fig.savefig(destination/(name+'.pdf'),bbox_inches='tight')
    plt.close(fig)


def make_figures(runs,destination):
    for metric,name,ylabel in [('eval_return','learning_curves','Undiscounted evaluation return'),
                               ('bias_q1','bias_curves_complete_only','Q1 - full Monte Carlo return')]:
        fig,axes=plt.subplots(1,2,figsize=(11,4),sharey=True)
        for ax,algo in zip(axes,('ddpg','td3')):
            for ln in (False,True):
                selected=group(runs,algo,ln)
                x=np.array([m['step'] for m in selected[0]['metrics']])/1000
                values=np.array([[np.nan if m[metric] is None else m[metric]
                                  for m in r['metrics']] for r in selected])
                for y in values:
                    ax.plot(x,y,color=COLORS[ln],alpha=.25,lw=.8)
                means=np.nanmean(values,axis=0)
                sd=np.nanstd(values,axis=0,ddof=1)
                ax.plot(x,means,color=COLORS[ln],lw=2,label='Critic LN on' if ln else 'Critic LN off')
                ax.fill_between(x,means-sd,means+sd,color=COLORS[ln],alpha=.15)
            ax.set(title=algo.upper(),xlabel='Training transitions (thousands)')
            ax.axhline(200 if metric=='eval_return' else 0,color='gray',ls='--',lw=.8)
            ax.grid(alpha=.2)
            ax.legend()
        axes[0].set_ylabel(ylabel)
        fig.suptitle('Pilot: 3 training seeds; thin lines = runs, band = ±1 seed SD',fontsize=11)
        if metric=='bias_q1':
            fig.text(.5,-.05,'Complete-only diagnostic: excludes censored episodes; selection bias is possible.',ha='center',fontsize=10)
        savefig(fig,destination,name)

    fig,axes=plt.subplots(1,2,figsize=(10,4))
    for ax,algo in zip(axes,('ddpg','td3')):
        for ln in (False,True):
            selected=group(runs,algo,ln)
            x=[r['long']['bias_q1'] for r in selected]
            y=[r['long']['eval_return'] for r in selected]
            ax.scatter(x,y,color=COLORS[ln],s=65,label='LN on' if ln else 'LN off')
            for r,xx,yy in zip(selected,x,y):
                ax.annotate(f"S{r['config']['seed']}",(xx,yy),xytext=(4,4),textcoords='offset points',fontsize=8)
        ax.axvline(0,color='gray',ls='--',lw=.8)
        ax.set(title=algo.upper(),xlabel='Signed Q1 error vs 10,000-step return')
        ax.grid(alpha=.2)
        ax.legend()
    axes[0].set_ylabel('Final evaluation return (1,000-step horizon)')
    fig.suptitle('One point per trained agent at 50,000 transitions; descriptive association',fontsize=11)
    savefig(fig,destination,'bias_vs_performance')

    fig,axes=plt.subplots(2,2,figsize=(10,9))
    for ax,(algo,ln) in zip(axes.flat,[(a,l) for a in ('ddpg','td3') for l in (False,True)]):
        selected=group(runs,algo,ln)
        actual=[]
        predicted=[]
        for run in selected:
            data=np.load(run['directory']/'calibration-long/pairs.npz',allow_pickle=False)
            actual.extend(data['mc'])
            predicted.extend(data['q'][:,0])
        actual=np.asarray(actual)
        predicted=np.asarray(predicted)
        ax.scatter(actual,predicted,s=5,alpha=.18,color=COLORS[ln])
        bounds=[min(actual.min(),predicted.min()),max(actual.max(),predicted.max())]
        ax.plot(bounds,bounds,'k--',lw=1,label='Q = return')
        ax.set(title=f'{algo.upper()} · critic LN {"on" if ln else "off"}',
               xlabel='Discounted 10,000-step return estimate',ylabel='Predicted Q1')
        ax.legend()
        ax.grid(alpha=.2)
    fig.suptitle('Final calibration: visited pairs from 3 agents × 10 episodes; pairs are correlated',fontsize=11)
    fig.tight_layout()
    savefig(fig,destination,'calibration')

    fig,axes=plt.subplots(1,2,figsize=(10,4))
    effects=paired_effects(runs)
    for ax,metric,label in zip(axes,('eval_return','bias_q1'),('Return change','Signed Q1 error change')):
        for x,algo in enumerate(('ddpg','td3')):
            row=next(r for r in effects if r['algorithm']==algo and r['metric']==metric)
            ax.scatter(np.full(3,x)+np.array([-.06,0,.06]),row['seed_differences'],color='#2874a6',s=40)
            ax.errorbar(x,row['mean_difference'],yerr=row['sd_difference'],color='black',fmt='_',ms=20,capsize=5)
        ax.set_xticks([0,1],['DDPG','TD3'])
        ax.set_ylabel(label+' (LN on minus off)')
        ax.axhline(0,color='gray',ls='--',lw=.8)
        ax.grid(axis='y',alpha=.2)
    fig.suptitle('Paired seed effects: points = seeds; black mark = mean ±1 sample SD',fontsize=11)
    savefig(fig,destination,'paired_effects')


def write_analysis(runs,destination):
    destination=Path(destination)
    rows=summaries(runs)
    effects=paired_effects(runs)
    for filename,data in [('summary.csv',rows),('paired_effects.csv',effects)]:
        with (destination/filename).open('w',newline='') as f:
            writer=csv.DictWriter(f,fieldnames=list(data[0]))
            writer.writeheader()
            writer.writerows(data)
    lines=['# LunarLander pilot results','',
           'Measured pilot: 12 runs, 3 training seeds per condition, 50,000 transitions per run.',
           'All ± values below are **sample standard deviations across training seeds**, not confidence intervals.','',
           '| Algorithm | Critic LN | Final return | Signed Q1 error | Q1 RMSE | Normalized learning-curve area |',
           '|---|---|---:|---:|---:|---:|']
    for row in rows:
        lines.append(f"| {row['algorithm'].upper()} | {'on' if row['layer_norm'] else 'off'} | "
            f"{row['return_mean']:.1f} ± {row['return_sd']:.1f} | "
            f"{row['bias_q1_mean']:.1f} ± {row['bias_q1_sd']:.1f} | "
            f"{row['rmse_q1_mean']:.1f} ± {row['rmse_q1_sd']:.1f} | "
            f"{row['normalized_auc_mean']:.1f} ± {row['normalized_auc_sd']:.1f} |")
    lines+=['','Performance is undiscounted reward up to 1,000 steps. Signed error compares Q1 with the discounted',
            'return of the same visited state/action pair under the frozen policy, using a 10,000-step diagnostic',
            'horizon. For natural termination that is a complete return; otherwise it is a finite approximation.','',
            '## Paired normalization effects','',
            '| Algorithm | Metric | Mean on-minus-off | SD of differences | Differences for seeds 0, 1, 2 |',
            '|---|---|---:|---:|---|']
    for row in effects:
        lines.append(f"| {row['algorithm'].upper()} | {row['metric']} | {row['mean_difference']:.1f} | "
                     f"{row['sd_difference']:.1f} | {', '.join(f'{d:.1f}' for d in row['seed_differences'])} |")
    original_censored=sum(r['metrics'][-1]['diagnostic_censored'] for r in runs)
    long_censored=sum(r['long']['censored_10000'] for r in runs)
    delta25=max(r['long']['delta_2500_5000_max'] for r in runs)
    delta50=max(r['long']['delta_5000_10000_max'] for r in runs)
    lines+=['','## Measurement audit','',
        f'The original final 5,000-step diagnostic censored {original_censored}/120 episodes. Complete-only bias',
        'therefore excludes some hovering policies. Its checkpoint curves are retained as a diagnostic',
        'and explicitly marked as conditional, not used as the main final comparison.',
        f'The supplemental 10,000-step diagnostic still censored {long_censored}/120 episodes but retains all of them.',
        f'Across all sampled final pairs, the largest 2,500→5,000 return change was {delta25:.3g};',
        f'the largest 5,000→10,000 change was {delta50:.3g}. This checks observed horizon sensitivity,',
        'not a mathematical bound on all possible future rewards. No critic prediction fills the missing tail.','',
        '## What we can conclude','',
        'These measurements describe early learning under one fixed configuration. A smaller signed error',
        'can mean less optimism or more pessimism; RMSE helps distinguish calibration quality from a sign shift.',
        'Layer normalization can affect optimization, actions and visited states as well as critic errors.',
        'Even when lower optimism accompanies better returns, that does not establish a causal effect of bias.',
        'Three training seeds provide little precision. Do not use 120 episodes or thousands of correlated',
        'trajectory pairs as if they were 120 or thousands of independent training runs.','',
        '## Next experiment','',
        'Use this pilot to choose a sufficient training budget. Freeze settings before collecting fresh',
        'training seeds (preferably 8–10) and held-out evaluation seeds. Retain the four-condition design.',
        'Extend the return-horizon sensitivity diagnostic to all checkpoints in the final study. Consider',
        'one min-versus-mean TD3 target ablation only after the main experiment is stable.']
    (destination/'analysis.md').write_text('\n'.join(lines)+'\n')
    return rows,effects
